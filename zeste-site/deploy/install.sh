#!/usr/bin/env bash
# Installe ou met à jour le site Zeste sur un VPS Ubuntu/Debian.
# Usage : sudo bash install.sh tondomaine.fr
# Relancer la même commande après avoir déposé une nouvelle version : c'est aussi la mise à jour.
set -euo pipefail

DOMAIN="${1:-}"; DOMAIN="${DOMAIN,,}"
DOMAIN="${DOMAIN#https://}"; DOMAIN="${DOMAIN#http://}"; DOMAIN="${DOMAIN#www.}"; DOMAIN="${DOMAIN%/}"
if [[ ! "$DOMAIN" =~ ^[a-z0-9.-]+\.[a-z]{2,}$ ]]; then
  echo "Usage : sudo bash install.sh tondomaine.fr" >&2; exit 1
fi
[[ "$(id -u)" -eq 0 ]] || { echo "Lance ce script avec sudo." >&2; exit 1; }

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
[[ -f "$SRC/dist/index.html" && -f "$SRC/deploy/server.py" ]] || { echo "Dossiers dist/ et deploy/ introuvables à côté du script." >&2; exit 1; }

echo "==> Paquets"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq python3 rsync curl gnupg >/dev/null
if ! command -v caddy >/dev/null; then
  curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/gpg.key' | gpg --dearmor --yes -o /usr/share/keyrings/caddy-stable-archive-keyring.gpg
  curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/debian.deb.txt' > /etc/apt/sources.list.d/caddy-stable.list
  apt-get update -qq && apt-get install -y -qq caddy >/dev/null
fi

echo "==> Fichiers du site dans /opt/zeste"
id zeste >/dev/null 2>&1 || useradd --system --no-create-home --shell /usr/sbin/nologin zeste
install -d -m 755 /opt/zeste
rsync -a --delete "$SRC/dist/" /opt/zeste/dist/
rsync -a --delete --exclude 'zeste.env' "$SRC/deploy/" /opt/zeste/deploy/
chown -R root:root /opt/zeste && chmod -R a+rX /opt/zeste

echo "==> Configuration du formulaire"
install -d -m 750 -o root -g zeste /etc/zeste
if [[ ! -f /etc/zeste/zeste.env ]]; then
  sed "s/__DOMAIN__/$DOMAIN/g" "$SRC/deploy/zeste.env.example" > /etc/zeste/zeste.env
  NEW_ENV=1
fi
chown root:zeste /etc/zeste/zeste.env && chmod 640 /etc/zeste/zeste.env

echo "==> Service"
install -m 644 "$SRC/deploy/zeste.service" /etc/systemd/system/zeste.service
systemctl daemon-reload
systemctl enable --now zeste >/dev/null
systemctl restart zeste

echo "==> HTTPS (Caddy)"
# Another web server (often a Docker proxy) holding 80/443 would leave the site unreachable.
BUSY="$(ss -tlnpH '( sport = :80 or sport = :443 )' 2>/dev/null | grep -v '"caddy"' || true)"
if [[ -n "$BUSY" ]]; then
  echo "!! Les ports 80/443 sont déjà utilisés par un autre programme :" >&2
  echo "$BUSY" | grep -o 'users:(("[^"]*"' | sort -u | sed 's/users:(("/   - /; s/"$//' >&2
  echo "   Le site tourne en local, mais pas encore sur https://$DOMAIN." >&2
  echo "   Libère ces ports (ex. docker ps puis docker stop <conteneur>) et relance ce script." >&2
  exit 1
fi
if [[ -f /etc/caddy/Caddyfile ]] && ! grep -q 'Generated by install.sh' /etc/caddy/Caddyfile; then
  cp /etc/caddy/Caddyfile "/etc/caddy/Caddyfile.avant-zeste.$(date +%s)"
fi
sed "s/__DOMAIN__/$DOMAIN/g" "$SRC/deploy/Caddyfile.template" > /etc/caddy/Caddyfile
caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null
systemctl enable caddy >/dev/null
systemctl reload caddy 2>/dev/null || systemctl restart caddy
sleep 1
systemctl is-active --quiet caddy || { echo "!! Caddy ne démarre pas : journalctl -u caddy -n 30" >&2; exit 1; }

if command -v ufw >/dev/null && ufw status | grep -q 'Status: active'; then
  ufw allow 80/tcp >/dev/null; ufw allow 443/tcp >/dev/null
fi

sleep 1
if curl -fsS -o /dev/null http://127.0.0.1:8099/; then echo "==> Site OK en local."; else echo "!! Le service ne répond pas : journalctl -u zeste -n 50" >&2; exit 1; fi
echo
echo "En ligne sur https://$DOMAIN (le certificat HTTPS peut prendre une minute la première fois)."
if [[ "${NEW_ENV:-}" == 1 ]] || grep -qE '^(SMTP_PASSWORD|MAIL_TO)=$' /etc/zeste/zeste.env; then
  echo "Formulaire : renseigne l'envoi des e-mails avec  sudo nano /etc/zeste/zeste.env"
  echo "puis                                          sudo systemctl restart zeste"
fi
